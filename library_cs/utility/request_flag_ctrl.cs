---------------------------------------------------------------------------*/

/*-------------------------------------------------------------------------
 using
---------------------------------------------------------------------------*/

/*-------------------------------------------------------------------------
 
---------------------------------------------------------------------------*/
namespace Utility
{
	/*-------------------------------------------------------------------------
	 
	---------------------------------------------------------------------------*/
	public class RequestCtrl
	{
		private bool						m_request;
		private object						m_arg1;			// 인수 1
		private object						m_arg2;			// 인수 2

		/*-------------------------------------------------------------------------
		 
		---------------------------------------------------------------------------*/
		public object Arg1{				get{	return m_arg1;			}}
		public object Arg2{				get{	return m_arg2;			}}

		/*-------------------------------------------------------------------------
		 
		---------------------------------------------------------------------------*/
		public RequestCtrl()
		{
			CancelRequest();
			m_arg1		= null;
			m_arg2		= null;
		}

		/*-------------------------------------------------------------------------
		 리퀘스트
		---------------------------------------------------------------------------*/
		public void Request()
		{
			m_request	= true;
			m_arg1		= null;
			m_arg2		= null;
		}
		public void Request(object arg1)
		{
			m_request	= true;
			m_arg1		= arg1;
			m_arg2		= null;
		}
		public void Request(object arg1, object arg2)
		{
			m_request	= true;
			m_arg1		= arg1;
			m_arg2		= arg2;
		}

		/*-------------------------------------------------------------------------
		 리퀘스트 취소
		 인수는 파기되지 않는다
		---------------------------------------------------------------------------*/
		public void CancelRequest()
		{
			m_request	= false;
		}

		/*-------------------------------------------------------------------------
		 리퀘스트 유무를 얻는다
		 플래그는 리퀘스트 없음으로 되돌아간다
		---------------------------------------------------------------------------*/
		public bool IsRequest()
		{
			bool	is_req	= m_request;
			CancelRequest();
			return is_req;
		}
	}
}
